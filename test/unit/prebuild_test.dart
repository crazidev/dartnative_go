    );
  });

  group('legacy asset cleanup', () {
    late Directory root;
    late Directory res;
    late Directory xcassets;

    setUp(() {
      root = Directory.systemTemp.createTempSync('dngo-legacy-assets-');
      addTearDown(() => root.deleteSync(recursive: true));
      res = Directory('${root.path}/android/app/src/main/res');
      xcassets = Directory('${root.path}/ios/Runner/Assets.xcassets');
    });

    File touch(String path) => File(path)
      ..createSync(recursive: true)
      ..writeAsStringSync('x');

    test('removes superseded Android and iOS assets', () {
      final legacy = [
        '${res.path}/drawable-mdpi/splash.png',
        '${res.path}/drawable-night-xxxhdpi/splash.png',
        '${res.path}/drawable/android12splash.png',
        '${res.path}/mipmap-hdpi/ic_launcher.png',
        '${res.path}/mipmap-hdpi/ic_launcher_round.png',
        '${res.path}/mipmap-hdpi/ic_launcher_foreground.png',
        '${res.path}/mipmap-hdpi/ic_launcher_monochrome.png',
        '${res.path}/mipmap-anydpi-v26/ic_launcher.xml',
        '${res.path}/mipmap-anydpi-v26/ic_launcher_round.xml',
        '${res.path}/mipmap-anydpi-v26/ic_launcher_foreground.png',
        '${res.path}/drawable-hdpi/ic_launcher_foreground.png',
        '${res.path}/drawable/ic_launcher_background.xml',
        '${res.path}/values/ic_launcher_background.xml',
        '${xcassets.path}/AppIcon.appiconset/AppIcon.png',
        '${xcassets.path}/AppIcon.appiconset/Icon-App-1024x1024@1x.png',
        '${xcassets.path}/LaunchImage.imageset/LaunchImage.png',
        '${xcassets.path}/LaunchBackground.imageset/background.png',
      ];
      final kept = [
        '${res.path}/mipmap-hdpi/custom_icon.png',
        '${res.path}/drawable-hdpi/splash_icon_legacy.png',
        '${res.path}/drawable/launch_background.xml',
        '${xcassets.path}/AppIcon.appiconset/Contents.json',
        '${xcassets.path}/LaunchBackground.colorset/Contents.json',
      ];
      for (final path in [...legacy, ...kept]) {
        touch(path);
      }

      removeLegacyGeneratedAssets(
        root,
        androidIcon: true,
        androidSplash: true,
        iosIcon: true,
        iosSplash: true,
      );

      for (final path in legacy) {
        expect(File(path).existsSync(), isFalse, reason: path);
      }
      for (final path in kept) {
        expect(File(path).existsSync(), isTrue, reason: path);
      }
      expect(
        Directory('${xcassets.path}/LaunchImage.imageset').existsSync(),
        isFalse,
      );
    });

    test('only clears families that are being regenerated', () {
      final legacy = [
        '${res.path}/drawable-mdpi/splash.png',
        '${res.path}/mipmap-hdpi/ic_launcher_foreground.png',
        '${xcassets.path}/AppIcon.appiconset/AppIcon.png',
        '${xcassets.path}/LaunchImage.imageset/LaunchImage.png',
      ];
      for (final path in legacy) {
        touch(path);
      }

      removeLegacyGeneratedAssets(
        root,
        androidIcon: false,
        androidSplash: false,
        iosIcon: false,
        iosSplash: false,
      );

      for (final path in legacy) {
        expect(File(path).existsSync(), isTrue, reason: path);
      }
    });
  });

  group('native project lifetime', () {
    Directory createProject() {
      final root = Directory.systemTemp.createTempSync('dngo-native-');
      addTearDown(() => root.deleteSync(recursive: true));
      Directory(
        '${root.path}/android/app/src/main',
      ).createSync(recursive: true);
      File(
        '${root.path}/android/app/build.gradle.kts',
      ).writeAsStringSync('applicationId = "com.example.app"');
      File(
        '${root.path}/android/app/src/main/AndroidManifest.xml',
      ).writeAsStringSync('<manifest/>');
      Directory('${root.path}/ios/Runner').createSync(recursive: true);
      Directory(
        '${root.path}/ios/Runner.xcodeproj',
      ).createSync(recursive: true);
      File(
        '${root.path}/ios/Podfile',
      ).writeAsStringSync("platform :ios, '16.1'");
      File(
        '${root.path}/ios/Runner/Info.plist',
      ).writeAsStringSync('<plist><dict/></plist>');
      return root;
    }

    test('keeps existing android and ios folders by default', () async {
      final root = createProject();
      final marker = File('${root.path}/android/app/src/main/manual.txt')
        ..writeAsStringSync('hand edited');

      await DngoNativeGenerator(root).ensureNativeProject();

      expect(
        File('${root.path}/android/app/build.gradle.kts').existsSync(),
        isTrue,
      );
      expect(File('${root.path}/ios/Runner/Info.plist').existsSync(), isTrue);
      expect(marker.readAsStringSync(), 'hand edited');
    });

    test('removeNativeProjectDirs drops only android and ios', () {
      final root = createProject();
      Directory('${root.path}/lib').createSync();
      File('${root.path}/pubspec.yaml').writeAsStringSync('name: app');

      removeNativeProjectDirs(root);

      expect(Directory('${root.path}/android').existsSync(), isFalse);
      expect(Directory('${root.path}/ios').existsSync(), isFalse);
      expect(Directory('${root.path}/lib').existsSync(), isTrue);
      expect(File('${root.path}/pubspec.yaml').existsSync(), isTrue);
    });
  });
}

/// Returns the `<activity>` element for [name] from a serialized manifest.
String _activity(String manifest, String name) {
  final match = manifest.indexOf('android:name="$name"');
  if (match < 0) return '';
  final open = manifest.lastIndexOf('<activity', match);
  final close = manifest.indexOf('</activity>', match);
  if (open < 0 || close < 0) return '';
  return manifest.substring(open, close + '</activity>'.length);
}
