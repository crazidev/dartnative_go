    await DngoNativeGenerator(root).generate(
      const DngoConfig(
        app: app,
        platforms: PlatformsConfig(
          ios: IosConfig(
            // `dartnativego` already exists in the scaffold plist; configuring
            // it must not make it a dngo-managed scheme.
            urlSchemes: {'dngo', 'dartnativego'},
            associatedDomains: {
              'applinks:example.com',
              'applinks:www.example.com',
            },
          ),
        ),
      ),
    );

    var plistText = plist.readAsStringSync();
    expect(plistText, contains('<string>dartnativego</string>'));
    expect(plistText, contains('<string>dngo</string>'));
    expect(plistText, contains('CFBundleURLName'));
    var entitlementsText = entitlements.readAsStringSync();
    expect(entitlementsText, contains('group.example'));
    expect(
      entitlementsText,
      contains('com.apple.developer.associated-domains'),
    );
