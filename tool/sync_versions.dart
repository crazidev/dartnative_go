import 'dart:io';

/// Regenerates `pkgs/dngo_api/lib/version.dart` from:
/// - root `pubspec.yaml` → dngo / runtime version
/// - root `dn_plugins.lock` → DartNative SDK (`Built with DartNative X.Y.Z`)
///
/// Run before compiling the CLI so `dngo --version` and the dev server share
/// the same baked-in numbers with zero startup cost.
void main(List<String> args) {
  final root = File(Platform.script.toFilePath()).parent.parent;
  final result = syncVersions(root);
  stdout.writeln(
    'Synced version.dart → dngo ${result.dngoVersion}, '
    'runtime ${result.runtimeVersion}, DartNative ${result.dartNativeVersion}',
  );
}

class SyncedVersions {
  const SyncedVersions({
    required this.dngoVersion,
    required this.runtimeVersion,
    required this.dartNativeVersion,
  });

  final String dngoVersion;
  final String runtimeVersion;
  final String dartNativeVersion;
}

/// Writes [version.dart] under [repoRoot]. Returns the values stamped.
SyncedVersions syncVersions(Directory repoRoot) {
  final dngo = _readPubspecVersion(repoRoot) ?? '0.0.0';
  final dartNative =
      _readDartNativeFromLock(repoRoot) ??
      _readDartNativeFromDnVersion() ??
      '0.0.0';

  final out = File(
    '${repoRoot.path}/pkgs/dngo_api/lib/version.dart',
  );
  out.parent.createSync(recursive: true);
  out.writeAsStringSync('''
/// Shared DartNative Go / DartNative SDK version constants.
///
/// GENERATED by `dart run tool/sync_versions.dart` (also run from
/// `tool/install_global.dart` before compiling). Do not edit by hand —
/// change `pubspec.yaml` / `dn_plugins.lock` and re-sync.
library;

/// The current version of the DartNative Go CLI and shell.
const String kDartGoVersion = '$dngo';

/// The corresponding DartNative Go mobile runtime version.
const String kDartGoRuntimeVersion = '$dngo';

/// The DartNative SDK version this DartNative Go release was built against.
///
/// Sourced from `dn_plugins.lock` ("Built with DartNative …").
const String kDartNativeVersion = '$dartNative';
''');

  return SyncedVersions(
    dngoVersion: dngo,
    runtimeVersion: dngo,
    dartNativeVersion: dartNative,
  );
}

String? _readPubspecVersion(Directory root) {
  final file = File('${root.path}/pubspec.yaml');
  if (!file.existsSync()) return null;
  for (final line in file.readAsLinesSync()) {
    final trimmed = line.trim();
    if (!trimmed.startsWith('version:')) continue;
    var raw = trimmed.substring('version:'.length).trim();
    if (raw.startsWith("'") || raw.startsWith('"')) {
      raw = raw.substring(1, raw.length - 1);
    }
    final plus = raw.indexOf('+');
    if (plus != -1) raw = raw.substring(0, plus);
    return raw.isEmpty ? null : raw;
  }
  return null;
}

String? _readDartNativeFromLock(Directory root) {
  final file = File('${root.path}/dn_plugins.lock');
  if (!file.existsSync()) return null;
  final match = RegExp(
    r'Built with DartNative\s+(\d+\.\d+\.\d+)',
  ).firstMatch(file.readAsStringSync());
  return match?.group(1);
}

/// Last-resort fallback when the lockfile is missing. Avoided during normal
/// sync because spawning `dn` is slower than a file read.
String? _readDartNativeFromDnVersion() {
  try {
    final result = Process.runSync('dn', ['--version'], runInShell: true);
    if (result.exitCode != 0) return null;
    final out = '${result.stdout}\n${result.stderr}';
    final match = RegExp(
      r'DartNative\s+(\d+\.\d+\.\d+)',
    ).firstMatch(out);
    return match?.group(1);
  } catch (_) {
    return null;
  }
}
